/* Browser contract for the private candidate preview; no patient content in code. */
const fs=require('fs'),path=require('path'),assert=require('assert'),{pathToFileURL}=require('url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const [input,output,initialId,episodeId]=process.argv.slice(2);
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.REVIEW_CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const errors=[],requests=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
  await page.goto(pathToFileURL(path.resolve(input)).href);
  const get=sel=>page.locator(sel).textContent();
  assert.equal(await page.locator('.review').count(),1);
  if(initialId)await page.locator('#checkpoint').selectOption(initialId);
  if(episodeId)await page.locator('#episode').selectOption(episodeId);
  const selected=await page.locator('#checkpoint').inputValue();
  const first=await page.locator('.target-summary').textContent();
  assert(first.includes(selected));assert(first.includes('尚未经专家确认'));
  assert(first.includes('文书检索时钟（不是临床选择时刻）'));
  await page.locator('#show-candidate-original').click();
  assert.equal(await page.locator('.researcher-only').getAttribute('open'),'');
  assert((await get('#panel-target')).includes('完整正文投影'));
  assert.equal(await page.locator('#panel-target [hidden]').count(),0);
  assert.equal(await page.locator('#panel-increment').isVisible(),true);
  assert.equal(await page.locator('#panel-timeline').isVisible(),false);
  assert((await get('#panel-increment')).includes('患者在这个 Checkpoint 的原始文书'));
  assert((await get('#panel-increment')).includes('Agent 选定理由'));
  assert((await get('#panel-increment')).includes('遮蔽范围与理由'));
  assert.equal(await page.locator('#panel-increment .neighbor-card').count(),2);
  await page.locator('.researcher-only summary').click();
  assert((await get('.researcher-only')).includes('发现阶段 LLM'));
  await page.locator('[data-tab="relations"]').click();
  assert.equal(await page.locator('#panel-relations').isVisible(),true);
  assert((await get('#panel-relations')).includes('Agent 连接理由'));
  const related=page.locator('#panel-relations [data-goto]').first();
  const relatedId=await related.getAttribute('data-goto');
  await related.click();
  assert.equal(await page.locator('#checkpoint').inputValue(),relatedId);
  assert.equal(await page.locator('.review').count(),1);
  assert((await get('.target-summary')).includes(relatedId));
  if(initialId)await page.locator('#checkpoint').selectOption(initialId);
  const next=page.locator('.checkpoint-nav button.next').first();
  assert.equal(await next.isEnabled(),true);
  const nextId=await next.getAttribute('data-goto');
  await next.click();assert.equal(await page.locator('#checkpoint').inputValue(),nextId);
  assert.equal(await page.locator('.checkpoint-nav button.previous').first().isEnabled(),true);
  await page.locator('.checkpoint-nav button.previous').first().click();assert.equal(await page.locator('#checkpoint').inputValue(),initialId);
  await page.locator('[data-tab="timeline"]').click();
  assert.equal(await page.locator('#panel-timeline').isVisible(),true);
  const sourceCount=await page.locator('#panel-timeline .source').count();
  assert(sourceCount>0);
  await page.locator('#source-filter').fill('THIS-SOURCE-DOES-NOT-EXIST');
  assert.equal(await page.locator('#panel-timeline .source:visible').count(),0);
  await page.locator('#source-filter').fill('');
  for(const day of await page.locator('#source-list .day').all())await day.evaluate(e=>e.open=true);
  assert.equal(await page.locator('#panel-timeline .source:visible').count(),sourceCount);
  await page.locator('[data-tab="evidence"]').click();
  assert.equal(await page.locator('#panel-evidence').isVisible(),true);
  await page.locator('[name="checkpoint_judgment"]').selectOption('uncertain');
  await page.locator('[name="note"]').fill('BROWSER-TEST-DRAFT');
  await page.locator('.review button[type="submit"]').click();
  await page.locator('#export').click();
  assert.equal(await page.locator('#download').isVisible(),true);
  const stored=await page.evaluate(id=>JSON.parse(localStorage.getItem('candidate-review-'+id)),initialId);
  assert.equal(stored.checkpoint_id,initialId);assert.equal(stored.note,'BROWSER-TEST-DRAFT');
  assert(stored.material_packet_content_sha256.length===64);
  assert.equal(stored.form_version,'development-preview-0.2');
  await page.locator('.checkpoint-nav button.next').first().click();
  assert.equal(await page.locator('[name="note"]').inputValue(),'');
  await page.locator('.checkpoint-nav button.previous').first().click();
  assert.equal(await page.locator('[name="note"]').inputValue(),'BROWSER-TEST-DRAFT');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.locator('[data-tab="increment"]').click();
  await page.evaluate(()=>{document.querySelector('.researcher-only').open=false;document.querySelector('.bar').style.position='static';});
  await page.screenshot({path:path.join(output,'preview-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.researcher-only summary').click();
  await page.screenshot({path:path.join(output,'preview-desktop.png'),fullPage:true});
  assert.equal(errors.length,0,errors.join('\n'));assert.equal(requests.length,0,requests.join('\n'));
  fs.writeFileSync(path.join(output,'browser-receipt.json'),JSON.stringify({status:'PASS',private_research_preview:true,doctor_release:false,initial_checkpoint_id:initialId,episode_id:episodeId,source_count:sourceCount,page_errors:errors,network_requests:requests,checks:['one_candidate_displayed','explicit_target_source_clock_and_function','researcher_original_separate_from_mask','related_candidate_click_navigation','previous_next_navigation','source_filter','evidence_panel','bound_local_draft','navigation_preserves_own_draft','mobile_no_horizontal_overflow']},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack);process.exit(1);});

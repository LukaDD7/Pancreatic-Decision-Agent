/* Actual browser checks, using only fictional assignments. */
const fs=require('fs'),path=require('path'),assert=require('assert'),{pathToFileURL}=require('url');
const {chromium}=require('playwright');
const [demo,xss,output]=process.argv.slice(2);
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.REVIEW_CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
 const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
 try{
  await page.goto(pathToFileURL(path.resolve(demo)).href);
  await page.locator('#main').waitFor({state:'visible'});
  assert.equal(await page.locator('input:checked').count(),0,'No prefilled answers');
  assert.equal(await page.locator('.material').count(),2);
  assert(!(await page.content()).includes('SYNTHETIC_HIDDEN_DECISION_AND_OUTCOME_43fb93'));
  await page.locator('#export-button').click();
  await page.locator('#answer-error').waitFor({state:'visible'});
  await page.getByLabel('演示模式 A',{exact:true}).check();
  await page.getByLabel('演示模式 B',{exact:true}).check();
  await page.getByLabel('演示动作甲',{exact:true}).check();
  await page.getByLabel('否',{exact:true}).check();
  const additional=page.getByLabel(/还需要哪些信息/);
  await additional.waitFor({state:'visible'});
  await additional.fill('需补充信息（虚构旧答案，条件关闭后必须清除）');
  await page.getByLabel('是',{exact:true}).check();
  await additional.waitFor({state:'hidden'});
  assert.equal(await additional.inputValue(),'','Disabled answer must be cleared');
  await page.getByRole('button',{name:'清除本题',exact:true}).click();
  assert.equal(await page.locator('input[type=radio]:checked').count(),0,'Can restore unanswered boolean');
  await page.getByLabel('否',{exact:true}).check();
  await additional.waitFor({state:'visible'});
  await page.locator('#export-button').click();
  await page.locator('#answer-error').waitFor({state:'visible'});
  assert((await page.locator('#answer-error').textContent()).includes('还需要哪些信息'));
  await additional.fill('需补充原始影像与相应临床资料（虚构测试意见）。');
  await page.getByLabel('其他说明（可选）',{exact:true}).fill('本文件仅用于接口测试，不是临床Reference。');
  await page.screenshot({path:path.join(output,'reader_desktop.png'),fullPage:true});
  const download=page.waitForEvent('download');
  await page.locator('#export-button').click();
  const file=await download;
  await file.saveAs(path.join(output,'browser-submission.json'));
  assert(!await page.locator('#answer-error').isVisible());
  const submission=JSON.parse(fs.readFileSync(path.join(output,'browser-submission.json'),'utf8'));
  const flatten=items=>items.flatMap(i=>[i,...flatten(i.item||[])]),answers=flatten(submission.questionnaire_response.item);
  assert.equal(answers.find(i=>i.linkId==='acceptable-modes').answer.length,2);
  assert.strictEqual(answers.find(i=>i.linkId==='information-sufficient').answer[0].valueBoolean,false);
  assert(!JSON.stringify(submission).includes('虚构旧答案'));
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'No mobile horizontal overflow');
  await page.screenshot({path:path.join(output,'reader_mobile.png'),fullPage:true});
  await page.goto(pathToFileURL(path.resolve(xss)).href);
  await page.locator('#main').waitFor({state:'visible'});
  assert.strictEqual(await page.evaluate(()=>window.XSS_EXECUTED),undefined);
  assert.equal(await page.locator('img').count(),0,'Literal source markup is not DOM');
  assert((await page.locator('#source-materials').textContent()).includes('<img'));
  assert.equal(requests.length,0,'Offline assignment must not make HTTP requests');
  assert.equal(errors.length,0,'No browser script errors');
  fs.writeFileSync(path.join(output,'browser_receipt.json'),JSON.stringify({status:'PASS',browser_version:browser.version(),synthetic_only:true,checks:['no_prefill','required_answers','multiple_acceptable_modes','conditional_required','clear_disabled_answers','clear_single_answer','actual_download','bound_response','mobile_layout','literal_markup','zero_http_requests','no_page_errors'],network_requests:requests.length,page_errors:errors},null,2)+'\n');
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack);process.exit(1);});

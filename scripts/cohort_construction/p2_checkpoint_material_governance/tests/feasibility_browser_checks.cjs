/* Synthetic-only browser checks for the private feasibility viewer. */
const fs=require('fs'),path=require('path'),assert=require('assert'),{pathToFileURL}=require('url');
const {chromium}=require('playwright');
const [input,output]=process.argv.slice(2);
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.REVIEW_CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const errors=[],requests=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
  await page.goto(pathToFileURL(path.resolve(input)).href);
  assert.equal(await page.locator('article.event').count(),2);
  assert.equal(await page.locator('.locate').count()>0,true);
  await page.locator('.locate').first().click();
  const mark=page.locator('#source-body mark.current');
  assert.equal(await mark.count(),1);
  const source=await page.locator('#source-body').textContent();
  assert(source.includes('当前决定：先行血管重建评估。'));
  assert.equal(await page.locator('.checkpoint-context').count(),2);
  assert.equal(await page.locator('.process-step').count(),2);
  assert((await page.locator('#source-body').textContent()).includes('虚构条件：未见远处转移。若血管可重建，可评估切除。'));
  assert((await page.locator('#source-body').textContent()).length>0);
  await page.locator('[data-process-event="EVENT-02"]').click();
  assert.equal(await page.locator('#event-select').inputValue(),'EVENT-02');
  assert((await page.locator('#source-body').textContent()).includes('[资料按方案遮蔽]'));
  assert(!(await page.locator('#source-body').textContent()).includes('决定：暂缓切除并补充病理证据。'));
  assert((await page.locator('#context-warning').textContent()).includes('不是已审定的正式盲评材料'));
  await page.locator('#show-original').click();
  await page.locator('#source-select').selectOption('DOC-02');
  assert((await page.locator('#source-body').textContent()).includes('决定：暂缓切除并补充病理证据。'));
  assert((await page.locator('#context-warning').textContent()).includes('可能包含当前选择及选择后信息'));
  await page.locator('[data-process-event="EVENT-01"]').click();
  await page.locator('#show-original').click();
  await page.locator('#source-select').selectOption('DOC-02');
  assert((await page.locator('#source-body').textContent()).includes('虚构复评'));
  await page.locator('.llm-output').first().click();
  assert.equal(await page.locator('[data-event="EVENT-01"] .llm-output .dimension').count()>0,true);
  assert((await page.locator('[data-event="EVENT-01"] .llm-output').textContent()).includes('程序'));
  await page.locator('[data-event="EVENT-02"] .locate').first().click();
  await page.locator('#show-original').click();
  await page.locator('#source-select').selectOption('DOC-02');
  assert.equal(await page.locator('#source-body mark').count(),0);
  assert((await page.locator('#source-body').textContent()).includes('虚构复评'));
  await page.locator('#toggle-forms').click();
  assert.equal(await page.locator('details.feedback[open]').count(),2);
  await page.locator('[data-event="EVENT-01"] [data-field="necessity"]').selectOption('VALID_DECISION_POINT');
  await page.locator('[data-event="EVENT-01"] [data-field="suggested_correction"]').fill('虚构浏览器测试建议');
  await page.locator('#episode-episode_overall').selectOption('FEASIBLE_WITH_REVISION');
  await page.locator('#reviewer-declaration').fill('SYNTHETIC-REVIEWER');
  await page.locator('#export').click();
  const response=JSON.parse(await page.locator('#export-output').textContent());
  assert.equal(response.review_sha256,JSON.parse(await page.locator('#review-data').textContent()).review_sha256);
  assert.equal(response.event_feedback[0].necessity,'VALID_DECISION_POINT');
  assert.equal(response.event_feedback[0].suggested_correction,'虚构浏览器测试建议');
  assert.equal(response.episode_feedback.episode_overall,'FEASIBLE_WITH_REVISION');
  assert.equal(response.reviewer_declaration,'SYNTHETIC-REVIEWER');
  assert.equal(response.doctor_answer_created,false);assert.equal(response.clinical_reference_created,false);
  fs.writeFileSync(path.join(output,'browser-response.json'),JSON.stringify(response,null,2));
  assert.equal(errors.length,0,errors.join('\n'));assert.equal(requests.length,0,requests.join('\n'));
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:path.join(output,'feasibility-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.locate').first().click();
  await page.screenshot({path:path.join(output,'feasibility-desktop.png'),fullPage:true});
  fs.writeFileSync(path.join(output,'browser-receipt.json'),JSON.stringify({status:'PASS',synthetic_only:true,network_requests:requests.length,page_errors:errors,checks:['process_overview','per_checkpoint_prechoice_context','projection_and_full_original_separation','source_citation_highlight','source_switch','llm_judgments_and_program_receipts','event_feedback','episode_feedback','response_bindings','no_clinical_answer','mobile_no_horizontal_overflow']},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack);process.exit(1);});
